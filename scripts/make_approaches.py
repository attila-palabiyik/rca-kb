"""Writes one KB approach folder, and one experiment file, per valid cell of the chart.

The chart is the table in docs/spec.md: what one entry is, against how entries
are indexed. Every folder is generated from it and from the shared
instruction pieces, so approaches differ only in the pieces they name. Change
the chart or a piece, then run this again:

    python scripts/make_approaches.py
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KB = ROOT / "configs" / "kb"
EXPERIMENTS = ROOT / "configs" / "experiments"

ENTRIES = ["transcript", "summary", "note", "rule", "page", "skill", "guide", "step"]
INDEXES = ["single_file", "flat_files", "catalogue", "signature_key", "tags", "hierarchy",
           "graph", "similarity"]

# One row per entry type, one mark per index: a name, "o" (valid, unnamed) or "-" (not valid).
CHART = {
    "transcript": ["shared-session", "raw-cases", "o", "o", "o", "o", "-", "o"],
    "summary":    ["o", "summaries", "o", "o", "o", "o", "-", "o"],
    "note":       ["o", "notes", "o", "o", "o", "o", "o", "o"],
    "rule":       ["playbook", "-", "-", "o", "o", "o", "-", "o"],
    "page":       ["-", "o", "wiki", "o", "o", "o", "wiki", "o"],
    "skill":      ["-", "-", "skills", "o", "o", "hierarchical-skills", "o", "o"],
    "guide":      ["o", "o", "o", "signature-guides", "o", "o", "o", "o"],
    "step":       ["o", "-", "-", "o", "-", "troubleshooting-tree", "o", "-"],
}

# Indexes whose top level is a file the agent CLI loads on its own.
LOADED_INDEXES = {"single_file", "catalogue", "signature_key", "tags", "hierarchy", "graph"}
# Indexes the agent has to keep up to date, so the approach has an Update turn.
AGENT_WRITTEN = "update_prompt"


def approaches() -> dict[str, dict]:
    """Every approach: its name, its cell or cells, and what its overlay holds."""
    found: dict[str, dict] = {}
    for entry, marks in CHART.items():
        for index, mark in zip(INDEXES, marks):
            if mark == "-":
                continue
            name = mark if mark != "o" else f"{entry}-{index}".replace("_", "-")
            found.setdefault(name, {"cells": []})["cells"].append((entry, index))
    for name, approach in found.items():
        approach["overlay"] = overlay(name, *approach["cells"][0])
    return found


def overlay(name: str, entry: str, index: str) -> dict:
    kb: dict = {"path": "/kb"}
    result: dict = {"instructions": ["_pieces/solve.md"], AGENT_WRITTEN: ["_pieces/update.md"]}

    if entry == "transcript":
        if index == "single_file":
            # One session continued through every task. The session is the KB.
            return {"agent_memory": {"session": "continue"},
                    "kb": {**kb, "cli_sessions": "sessions"}}
        if index in ("flat_files", "similarity"):
            kb["cli_sessions"] = "sessions"
            piece = "flat_transcripts" if index == "flat_files" else "similarity_transcripts"
            return {"instructions": [*result["instructions"], "_pieces/entry/transcript.md",
                                     f"_pieces/index/{piece}.md"], "kb": kb}
        result["instructions"] += ["_pieces/entry/transcript_indexed.md", f"_pieces/index/{index}.md"]
    elif name == "wiki":
        result["instructions"] += ["_pieces/entry/page.md", "_pieces/index/wiki.md"]
    elif name in ("skills", "hierarchical-skills"):
        piece = "cli_skills" if name == "skills" else "cli_skills_hierarchy"
        result["instructions"] += ["_pieces/entry/skill.md", f"_pieces/index/{piece}.md"]
        kb["links"] = {"/root/.agents/skills": "skills"}
        result["kb"] = kb
        return result
    else:
        result["instructions"] += [f"_pieces/entry/{entry}.md", f"_pieces/index/{index}.md"]

    if index in LOADED_INDEXES or name == "wiki":
        kb["links"] = {"/app/AGENTS.md": "AGENTS.md"}
    result["kb"] = kb
    return result


def toml(data: dict, header: str) -> str:
    lines = [header, ""]
    tables = {k: v for k, v in data.items() if isinstance(v, dict)}
    for key, value in data.items():
        if key in tables:
            continue
        items = ",\n".join(f"    {json.dumps(v)}" for v in value)
        lines.append(f"{key} = [\n{items},\n]")
    for key, table in tables.items():
        nested = {k: v for k, v in table.items() if isinstance(v, dict)}
        lines += ["", f"[{key}]"]
        lines += [f"{k} = {json.dumps(v)}" for k, v in table.items() if k not in nested]
        for sub, values in nested.items():
            lines += ["", f"[{key}.{sub}]"]
            lines += [f"{json.dumps(k)} = {json.dumps(v)}" for k, v in values.items()]
    return "\n".join(lines) + "\n"


EXPERIMENT = """# {title}: built on A, frozen, run on B, with its empty-KB control.
# Generated by scripts/make_approaches.py.

dataset = "chipbench"
split   = "main"
repeats = 3
seed    = 1
max_parallel = 10
retries = 2

[monitor]
judge_model = "gpt-6.2-sol"
rubric      = "v1"
assessment  = "v1"

[[conditions]]
name = "build"
mode = "build"
kb   = "{name}"
side = ["A"]

[[conditions]]
name     = "eval"
mode     = "eval"
kb       = "{name}"
side     = ["B"]
snapshot = "build"

[[conditions]]
name     = "empty"
mode     = "eval"
kb       = "{name}"
side     = ["B"]
snapshot = "seed"
"""


def main() -> None:
    found = approaches()
    for folder in KB.iterdir():
        overlay_file = folder / "overlay.toml"
        if overlay_file.is_file() and "Generated by scripts/make_approaches.py" in overlay_file.read_text():
            shutil.rmtree(folder)
    for old in EXPERIMENTS.glob("kb-*.toml"):
        old.unlink()
    for name, approach in sorted(found.items()):
        cells = " and ".join(f"{e} x {i}" for e, i in approach["cells"])
        header = (f"# {name}: {cells}.\n"
                  "# Generated by scripts/make_approaches.py from the chart; edit the chart, not this file.")
        (KB / name).mkdir(parents=True)
        (KB / name / "overlay.toml").write_text(toml(approach["overlay"], header), encoding="utf-8",
                                                newline="\n")
        (EXPERIMENTS / f"kb-{name}.toml").write_text(
            EXPERIMENT.format(title=name, name=name), encoding="utf-8", newline="\n")
    print(f"{len(found)} approaches written: {', '.join(sorted(found))}")


if __name__ == "__main__":
    main()
