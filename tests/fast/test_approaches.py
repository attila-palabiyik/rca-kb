"""The generated approach folders match the chart and load cleanly."""

import importlib.util
from pathlib import Path

from harness.config.load import apply_overlay, load_base
from harness.records.store import Run, _void_rest_of_chain

from ..conftest import REPO

spec = importlib.util.spec_from_file_location("make_approaches", REPO / "scripts" / "make_approaches.py")
make_approaches = importlib.util.module_from_spec(spec)
spec.loader.exec_module(make_approaches)


def test_every_valid_cell_of_the_chart_has_a_folder_and_an_experiment():
    wanted = set(make_approaches.approaches())
    folders = {p.parent.name for p in (REPO / "configs" / "kb").glob("*/overlay.toml")
               if "Generated by scripts/make_approaches.py" in p.read_text()}
    experiments = {p.stem.removeprefix("kb-") for p in (REPO / "configs" / "experiments").glob("kb-*.toml")}
    assert folders == wanted == experiments
    valid_cells = sum(mark != "-" for marks in make_approaches.CHART.values() for mark in marks)
    assert valid_cells == 52 and len(wanted) == 51          # the wiki takes two cells


def test_every_approach_applies_to_the_base_setup():
    configs = REPO / "configs"
    base = load_base(configs)
    for name in make_approaches.approaches():
        setup = apply_overlay(base, configs, name)
        assert setup.rules == base.rules and setup.model == base.model
        continued = setup.agent_memory["session"] == "continue"
        assert bool(setup.instructions) != continued, name   # only the shared session says nothing
        if "cli_sessions" in setup.kb and "transcript_indexed" not in str(
                (configs / "kb" / name / "overlay.toml").read_text()):
            assert setup.update_prompt == "", name           # the CLI writes these, not the agent


def test_approaches_differ_only_in_the_pieces_they_name():
    base = load_base(REPO / "configs")
    notes = apply_overlay(base, REPO / "configs", "notes")
    tagged = apply_overlay(base, REPO / "configs", "note-tags")
    skeleton = (REPO / "configs" / "kb" / "_pieces" / "solve.md").read_text().strip()
    assert notes.instructions.startswith(skeleton) and tagged.instructions.startswith(skeleton)
    assert notes.update_prompt == tagged.update_prompt
    assert notes.instructions != tagged.instructions


def test_no_piece_gives_debugging_advice_about_the_benchmark():
    """Pieces describe the KB, never how to fix a bug."""
    for piece in (REPO / "configs" / "kb" / "_pieces").rglob("*.md"):
        if piece.name == "redteam.md":
            continue
        text = piece.read_text().lower()
        for word in ("minimal fix", "reset value", "always block", "blocking assign", "off-by-one"):
            assert word not in text, f"{piece.name}: {word}"


def build_run(position, review=None):
    return Run(Path("."), {"condition": {"name": "build", "mode": "build"}, "repeat": 0,
                           "position": position, "run_id": f"r{position}", "task_id": "t",
                           "status": "completed", "phases": {}, "kb": {}},
               {"result": "pass"}, {"status": "certified"}, None,
               {"decision": review} if review else None)


def test_a_void_build_run_voids_the_rest_of_its_chain():
    runs = [build_run(0), build_run(1, "void"), build_run(2), build_run(3)]
    _void_rest_of_chain(runs)
    assert [r.result for r in runs] == ["pass", "fail", "fail", "fail"]
